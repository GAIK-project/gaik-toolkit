"""Machine-readable marks on what the demo hands out as AI-generated.

Three carriers, each where the file type has one:

- HTTP headers on the routes that serve a generated file (``X-AI-Generated``,
  ``X-AI-Generator``), added by ``AIMarkMiddleware``.
- PDF document metadata (creator, subject, keywords) on the PDFs the demo
  renders from model output.
- Metadata inside synthetic speech: an ID3v2.3 tag on MP3 and a LIST/INFO
  chunk on WAV. The other audio formats carry the response field and header.

The values follow IPTC's digital source type for content made by a trained
model.
"""

from __future__ import annotations

import re
import struct

GENERATOR = "GAIK toolkit demo"
DIGITAL_SOURCE_TYPE = "http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"
NOTE = f"AI-generated by {GENERATOR}; digital source type: trainedAlgorithmicMedia"

HEADERS = {"X-AI-Generated": "true", "X-AI-Generator": GENERATOR}

# API paths (after the proxy strips /api) that serve a file a model produced.
_GENERATED_DOWNLOADS = re.compile(
    r"^/(?:"
    r"pipeline/pdf/[^/]+"
    r"|diary/pdf/[^/]+"
    r"|luvata-order/pdf/[^/]+"
    r"|dental-transcribe/(?:srt|vtt)/[^/]+"
    r"|wizard/download/[^/]+"
    r"|text-to-speech"
    r")$"
)


def is_generated_download(path: str) -> bool:
    return bool(_GENERATED_DOWNLOADS.match(path))


class AIMarkMiddleware:
    """Adds ``HEADERS`` to the responses of the generated-download routes."""

    def __init__(self, app) -> None:
        self.app = app

    async def __call__(self, scope, receive, send) -> None:
        if scope["type"] != "http" or not is_generated_download(scope.get("path", "")):
            await self.app(scope, receive, send)
            return

        async def send_marked(message) -> None:
            if message["type"] == "http.response.start" and message.get("status", 500) < 400:
                headers = list(message.get("headers", []))
                headers += [(k.lower().encode(), v.encode()) for k, v in HEADERS.items()]
                message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_marked)


def mark_pdf(pdf) -> None:
    """Write the marks into an ``fpdf.FPDF`` document's metadata."""
    pdf.set_creator(GENERATOR)
    pdf.set_subject(NOTE)
    pdf.set_keywords("ai_generated, trainedAlgorithmicMedia")


# --------------------------------------------------------------------- audio


def _syncsafe(size: int) -> bytes:
    return bytes(((size >> shift) & 0x7F) for shift in (21, 14, 7, 0))


def _txxx(description: str, value: str) -> bytes:
    # Encoding 0 (ISO-8859-1): ID3v2.3 defines only 0 and 1 (UTF-16), so a
    # strict reader drops a frame marked 3 (UTF-8). The marks are ASCII.
    text = description.encode("latin-1", "replace") + b"\x00" + value.encode("latin-1", "replace")
    body = b"\x00" + text
    return b"TXXX" + struct.pack(">I", len(body)) + b"\x00\x00" + body


def mark_mp3(data: bytes) -> bytes:
    """Prepend an ID3v2.3 tag with the marks (an existing tag is kept after it)."""
    frames = (
        _txxx("AI_GENERATED", "true")
        + _txxx("AI_GENERATOR", GENERATOR)
        + _txxx("DIGITAL_SOURCE_TYPE", DIGITAL_SOURCE_TYPE)
    )
    return b"ID3\x03\x00\x00" + _syncsafe(len(frames)) + frames + data


def mark_wav(data: bytes) -> bytes:
    """Append a LIST/INFO chunk with the marks and fix the RIFF size."""
    if not (data.startswith(b"RIFF") and data[8:12] == b"WAVE"):
        return data

    def sub(chunk_id: bytes, text: str) -> bytes:
        value = text.encode() + b"\x00"
        if len(value) % 2:
            value += b"\x00"
        return chunk_id + struct.pack("<I", len(value)) + value

    info = b"INFO" + sub(b"ICMT", NOTE) + sub(b"ISFT", GENERATOR)
    body = data if len(data) % 2 == 0 else data + b"\x00"
    marked = body + b"LIST" + struct.pack("<I", len(info)) + info
    return marked[:4] + struct.pack("<I", len(marked) - 8) + marked[8:]


def mark_audio(data: bytes, response_format: str) -> bytes:
    if response_format == "mp3":
        return mark_mp3(data)
    if response_format == "wav":
        return mark_wav(data)
    return data
