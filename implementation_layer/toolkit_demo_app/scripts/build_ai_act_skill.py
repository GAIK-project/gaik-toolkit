"""Build the demo's copy of the EU AI Act screening skill text.

The AI Act screening demo (app/api/ai-act-screening) gives its agent the skill's own
instructions and references. The demo image is built from toolkit_demo_app/ alone, so the
text is a committed copy of the skill under implementation_layer/no-code-assets:

    lib/ai-act-screening/skill.generated.ts

Run it after any change to the skill:

    uv run python implementation_layer/toolkit_demo_app/scripts/build_ai_act_skill.py

`--check` exits non-zero when the committed copy is stale; a unit test runs it.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parents[1]
SKILL_DIR = (
    APP_DIR.parent / "no-code-assets" / "agent-skills" / "skills" / "ai-act-use-case-screening"
)
OUT = APP_DIR / "lib" / "ai-act-screening" / "skill.generated.ts"


def read(relative: str) -> str:
    return (SKILL_DIR / relative).read_text(encoding="utf-8").replace("\r\n", "\n").strip()


def build() -> str:
    skill = re.sub(r"\A---\n.*?\n---\n", "", read("SKILL.md"), count=1, flags=re.S).strip()
    output_format = read("references/output-format.md")
    # The demo has no report file: the report for people is the results page.
    output_format = output_format.split("\n## 3. ")[0].strip()
    reference = read("references/ai-act-reference.md")
    verified = re.search(r"^last_verified:\s*(\S+)", reference, re.M)
    if not verified:
        raise SystemExit("ai-act-reference.md has no last_verified date")
    parts = {
        "referenceLastVerified": verified.group(1),
        "skill": skill,
        "questionBank": read("references/question-bank.md"),
        "outputFormat": output_format,
        "reference": reference,
    }
    lines = [
        "// Generated by scripts/build_ai_act_skill.py from the ai-act-use-case-screening",
        "// skill. Do not edit; run the script after changing the skill.",
        "",
        "// prettier-ignore",
        "export const SKILL_TEXT = {",
    ]
    for key, value in parts.items():
        lines.append(f"  {key}: {json.dumps(value, ensure_ascii=False)},")
    lines += ["} as const;", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("stale: run scripts/build_ai_act_skill.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(APP_DIR)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
