"""Proof of Concept: Finnish Voice Fault Reporting — Maintenance Ticket Generator

Generated by GAIK Solution Configuration Wizard V2.
Pattern: audio_to_structured (AudioToStructuredData module)

Usage:
    python run_poc.py                   # expects a file in sample_input/
    python run_poc.py --input my.wav    # specify input directly
    python run_poc.py --synthetic       # generate a synthetic sample
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml
from dotenv import load_dotenv

load_dotenv()

sys.path.insert(0, str(Path(__file__).parent.parent.parent.parent.parent / "src"))

from gaik.software_modules.audio_to_structured_data import AudioToStructuredData  # noqa: E402


def load_config() -> dict:
    config_path = Path(__file__).parent / "config.yaml"
    with open(config_path) as f:
        return yaml.safe_load(f)


def load_requirements() -> str:
    req_path = Path(__file__).parent / "prompts" / "extraction_requirements.md"
    return req_path.read_text(encoding="utf-8")


def _requirements_hash() -> str:
    """SHA-256 of extraction_requirements.md -- used to detect prompt changes."""
    import hashlib
    req_path = Path(__file__).parent / "prompts" / "extraction_requirements.md"
    return hashlib.sha256(req_path.read_bytes()).hexdigest()


def _load_schema_if_fresh(pipeline, schema_dir: Path, schema_name: str):
    """Load the saved schema if it exists and the requirements prompt hasn't changed.

    Returns (schema, requirements_obj, current_hash) where schema/requirements_obj
    are None if the schema should be regenerated.

    Three cases:
      - Hash matches and schema loads  → use saved schema (Issue 1 fix)
      - Hash mismatch                  → prompt changed, must regenerate (Issue 2 fix)
      - No hash / no schema files      → first run, generate normally
    """
    current_hash = _requirements_hash()
    hash_path = schema_dir / f"{schema_name}.hash"

    if hash_path.exists():
        stored_hash = hash_path.read_text().strip()
        if stored_hash != current_hash:
            print(
                "extraction_requirements.md has changed since the schema was last generated.\n"
                "Regenerating schema to reflect the updated prompt..."
            )
            return None, None, current_hash

    try:
        existing = pipeline.load_schema(schema_dir, schema_name)
        if existing:
            print("Using approved schema (requirements unchanged).")
            return existing[0], existing[1], current_hash
        # Schema files absent
        print("No saved schema found -- will generate from extraction_requirements.md.")
        return None, None, current_hash
    except Exception as exc:
        import traceback as _tb
        print(
            f"\nERROR: The approved schema exists but could not be loaded.\n"
            f"  Schema       : {schema_dir}/{schema_name}.py\n"
            f"  Requirements : {schema_dir}/{schema_name}_requirements.json\n"
            f"  Reason       : {type(exc).__name__}: {exc}\n\n"
            f"{_tb.format_exc()}"
            f"The approved schema has NOT been overwritten.\n"
            f"To regenerate, delete the two files above and re-run.\n",
            file=sys.stderr,
        )
        sys.exit(1)


def find_input_file(config: dict, cli_input: str | None) -> Path:
    if cli_input:
        p = Path(cli_input)
        if not p.exists():
            print(f"ERROR: Input file not found: {p}", file=sys.stderr)
            sys.exit(1)
        return p

    sample_dir = Path(__file__).parent / config.get("paths", {}).get("sample_input", "sample_input")
    audio_exts = (".wav", ".mp3", ".m4a", ".ogg", ".flac", ".webm", ".mp4")
    files = [f for f in sample_dir.iterdir() if f.suffix.lower() in audio_exts]
    if not files:
        print(
            f"ERROR: No audio file found in {sample_dir}\n"
            "Place a .wav or .mp3 file there, or use --input to specify one.",
            file=sys.stderr,
        )
        sys.exit(1)
    return sorted(files)[0]


def main() -> None:
    parser = argparse.ArgumentParser(description="Finnish Voice Fault Reporting — Maintenance Ticket Generator PoC")
    parser.add_argument("--input", help="Path to audio file (overrides sample_input/)")
    parser.add_argument(
        "--synthetic",
        action="store_true",
        help="Audio input cannot be synthesised automatically. Place a real .wav or .mp3 in sample_input/ instead.",
    )
    args = parser.parse_args()

    if args.synthetic:
        print(
            "INFO: Audio input cannot be auto-generated.\n"
            "Please place a real Finnish voice recording (.wav or .mp3) in sample_input/ and re-run."
        )
        sys.exit(0)

    config = load_config()
    user_requirements = load_requirements()
    use_azure = config.get("use_azure", True)
    models = config.get("models", {})
    language = config.get("language", "fi")
    transcription_model = models.get("transcription", "gpt-4o-transcribe")
    extraction_model = models.get("extraction")

    print(f"Loading pipeline: AudioToStructuredData (use_azure={use_azure})")
    print(f"  Transcription model : {transcription_model}")
    print(f"  Extraction model    : {extraction_model or 'provider default'}")
    print(f"  Language            : {language}")
    pipeline = AudioToStructuredData(use_azure=use_azure)

    input_file = find_input_file(config, args.input)
    print(f"Input file: {input_file}")

    schema_dir = Path(__file__).parent / config.get("paths", {}).get("schemas", "schemas")
    schema_name = "output_schema"

    schema, requirements_obj, _current_hash = _load_schema_if_fresh(pipeline, schema_dir, schema_name)

    transcriber_ctor = {
        "output_dir": str(Path(__file__).parent / "output"),
        "compress_audio": True,
        "enhanced_transcript": True,
        "transcription_model": transcription_model,
        "language": language,
    }
    extractor_ctor = {}
    if extraction_model:
        extractor_ctor["model"] = extraction_model

    result = pipeline.run(
        file_path=input_file,
        user_requirements=user_requirements,
        transcriber_ctor=transcriber_ctor,
        transcribe_options={"use_case_name": "maintenance_ticket"},
        extractor_ctor=extractor_ctor,
        extract_options={"save_json": False},
        schema=schema,
        requirements=requirements_obj,
    )

    # Persist schema files when freshly generated, and always write the hash.
    # Writing the hash on every successful run (not just after generation) ensures
    # that a later change to extraction_requirements.md is detected on the next run.
    if result.schema and result.requirements and schema is None:
        try:
            pipeline.save_schema(result.schema, result.requirements, schema_dir, schema_name)
            print(f"Schema saved to {schema_dir}/")
        except Exception as exc:
            print(f"WARNING: Could not save schema: {exc}")
    hash_path = schema_dir / f"{schema_name}.hash"
    try:
        hash_path.write_text(_current_hash)
    except Exception as exc:
        print(f"WARNING: Could not write schema hash: {exc}")

    # Define output_dir early so it is available inside the LLMJudge block below.
    output_dir = Path(__file__).parent / config.get("paths", {}).get("output", "output")
    output_dir.mkdir(parents=True, exist_ok=True)

    # -- LLMJudge hallucination detection (from blueprint) --
    # detect_hallucinations() checks each extracted field against the grounding
    # source text and flags any value not supported by it.
    # Uses OpenAI provider; use_azure is read from config (True for Azure OpenAI).
    print("\nRunning LLMJudge hallucination detection...")
    try:
        from gaik.software_components.validators.llm_judge.llm_judge import LLMJudge as _LLMJudge
        judge = _LLMJudge(model_provider="openai", use_azure=use_azure)

        # Resolve source text: transcript for audio pipelines, parsed document for document pipelines
        source_text = ""
        if hasattr(result, "transcription") and result.transcription:
            source_text = (
                getattr(result.transcription, "enhanced_transcript", None)
                or getattr(result.transcription, "raw_transcript", None)
                or ""
            )
        elif hasattr(result, "parsed_documents") and result.parsed_documents:
            source_text = "\n\n".join(result.parsed_documents)

        if source_text and result.extracted_fields:
            # The Extractor returns a list (multi-document pipeline).
            # detect_hallucinations() expects a plain dict, so unwrap
            # the first element for single-document PoC runs.
            extracted_for_judge = result.extracted_fields
            if isinstance(extracted_for_judge, list) and len(extracted_for_judge) == 1:
                extracted_for_judge = extracted_for_judge[0]
            report = judge.detect_hallucinations(
                source_text=source_text,
                extracted=extracted_for_judge,
            )
            if report.flags:
                print(f"WARNING: {len(report.flags)} hallucination flag(s) detected:")
                for flag in report.flags:
                    print(f"  field={flag.field}  value={flag.value}  reason={flag.reason}")
            else:
                print("Hallucination check passed -- all fields are grounded in the source.")
            validation_result = {
                "hallucination_flags": [
                    {"field": f.field, "value": f.value, "severity": str(f.severity), "reason": f.reason}
                    for f in report.flags
                ],
                "passed": len(report.flags) == 0,
            }
            val_path = output_dir / f"{input_file.stem}_validation.json"
            val_path.write_text(
                json.dumps(validation_result, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
            print(f"Validation report: {val_path}")
        else:
            print("LLMJudge skipped: no source text available for grounding.")
    except ImportError:
        print("LLMJudge skipped: gaik[llm-judge] not installed.")
    except Exception as _judge_exc:
        print(f"LLMJudge warning: {_judge_exc}")

    # -- Human review (blueprint step: supervisor_review) --
    print("\nNOTE: Human review (supervisor approval) is not executed in the PoC.")
    print("      Gate 3 in the wizard conversation is the equivalent review step.")
    print("      In production, the approved_ticket artifact is produced here.")

    # Save output
    output_path = output_dir / f"{input_file.stem}_ticket.json"
    output_path.write_text(
        json.dumps(result.extracted_fields, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )

    print(f"\nExtracted fields written to: {output_path}")
    print(json.dumps(result.extracted_fields, indent=2, ensure_ascii=False, default=str))

    if result.transcription:
        transcript_path = output_dir / f"{input_file.stem}_transcript.txt"
        raw = getattr(result.transcription, "raw_transcript", None)
        enhanced = getattr(result.transcription, "enhanced_transcript", None)
        transcript_text = enhanced or raw or ""
        if transcript_text:
            transcript_path.write_text(transcript_text, encoding="utf-8")
            print(f"Transcript saved to: {transcript_path}")

    _pdf_source = result.extracted_fields


if __name__ == "__main__":
    main()
