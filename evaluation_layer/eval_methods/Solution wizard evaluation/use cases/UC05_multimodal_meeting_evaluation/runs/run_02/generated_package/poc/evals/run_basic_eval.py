"""Basic evaluation script for AI-Supported Meeting Record Generation.

Evaluation framework: extraction_eval (specialised for the MeetingRecord shape)
Generated by GAIK Solution Configuration Wizard, refined for this use case.

Checks (per technical_spec.evaluation_requirements):
  1. Citation format validity -- every citations[] entry in decisions, action_items,
     unresolved_issues, and conflicts must be a pipe-delimited string matching:
       audio:  file_name|HH:MM:SS|HH:MM:SS
       agenda: file_name|page_number
  2. Structural completeness -- every decision/action_item/unresolved_issue/conflict
     has at least one citation; review_status == "pending_review".
  3. Field-level comparison against a ground-truth file (if present in
     evals/ground_truth/<output_filename>), for the flat top-level fields plus
     decision/action counts.
  4. must_not_assert check -- if the ground-truth file carries a "must_not_assert"
     list (statements the output must never claim), do a keyword-overlap heuristic
     against the output text and flag any hits for manual review. This is a basic
     heuristic, not a semantic judge -- treat flags as "look at this", not a hard fail.

Usage:
    python evals/run_basic_eval.py [--output-file output/meeting_record.json]

Expects:
    output/             -- PoC output (run run_poc.py first)
    evals/ground_truth/  -- optional ground-truth JSON, same filename as the output
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

AUDIO_CITATION_RE = re.compile(r"^[^|]+\|[0-9]{2}:[0-9]{2}:[0-9]{2}\|[0-9]{2}:[0-9]{2}:[0-9]{2}$")
AGENDA_CITATION_RE = re.compile(r"^[^|]+\|[0-9]+$")

ITEM_CONTAINERS = ("decisions", "action_items", "unresolved_issues", "conflicts")


def _is_valid_citation(citation: str) -> bool:
    return bool(AUDIO_CITATION_RE.match(citation) or AGENDA_CITATION_RE.match(citation))


def check_citation_format(record: dict) -> list[str]:
    """Return a list of problems found in citation formatting/coverage."""
    problems = []
    for container in ITEM_CONTAINERS:
        for i, item in enumerate(record.get(container, [])):
            citations = item.get("citations", [])
            if not citations:
                problems.append(f"{container}[{i}] has no citations (at least one required)")
                continue
            for c in citations:
                if not isinstance(c, str) or not _is_valid_citation(c):
                    problems.append(f"{container}[{i}] has a malformed citation: {c!r}")
    return problems


def check_structural_completeness(record: dict) -> list[str]:
    problems = []
    required_top_level = [
        "meeting_id", "title", "meeting_date", "start_time", "end_time",
        "participants", "topics", "decisions", "action_items",
        "unresolved_issues", "conflicts", "review_status",
    ]
    for field in required_top_level:
        if field not in record:
            problems.append(f"Missing top-level field: {field}")
    if record.get("review_status") != "pending_review":
        problems.append(
            f"review_status should be 'pending_review', got {record.get('review_status')!r}"
        )
    for i, action in enumerate(record.get("action_items", [])):
        if (action.get("owner") is None or action.get("due_date") is None) and not action.get(
            "uncertainty_reason"
        ):
            problems.append(
                f"action_items[{i}] has a null owner/due_date but no uncertainty_reason"
            )
    return problems


def check_must_not_assert(record: dict, must_not_assert: list[str]) -> list[str]:
    """Heuristic keyword-overlap check -- flags for manual review, not a hard fail."""
    flags = []
    record_text = json.dumps(record, ensure_ascii=False).lower()
    for statement in must_not_assert:
        # crude heuristic: pull out the "content" words (>=4 chars) and see how many
        # appear in the output; a high hit-rate suggests the forbidden claim may have
        # leaked in and deserves a human look.
        words = [w for w in re.findall(r"[a-zA-Z0-9]+", statement.lower()) if len(w) >= 4]
        if not words:
            continue
        hits = sum(1 for w in words if w in record_text)
        ratio = hits / len(words)
        if ratio >= 0.8:
            flags.append(f"Possible forbidden assertion (heuristic {ratio:.0%} keyword match): {statement!r}")
    return flags


def compare_to_ground_truth(record: dict, ground_truth: dict) -> tuple[int, int]:
    """Compare simple scalar top-level fields + item counts. Returns (matches, total)."""
    matches = total = 0
    for field in ("meeting_id", "title", "meeting_date", "start_time", "end_time", "review_status"):
        if field in ground_truth:
            total += 1
            if str(record.get(field, "")).strip().lower() == str(ground_truth[field]).strip().lower():
                matches += 1
    for container in ITEM_CONTAINERS + ("participants", "topics"):
        if container in ground_truth:
            total += 1
            if len(record.get(container, [])) == len(ground_truth[container]):
                matches += 1
    return matches, total


def run_evaluation(output_path: Path, ground_truth_dir: Path) -> None:
    if not output_path.exists():
        print(f"No output file found at {output_path}")
        print("Run run_poc.py first to generate output.")
        return

    record = json.loads(output_path.read_text(encoding="utf-8"))

    print(f"Evaluating: {output_path}")
    print("=" * 70)

    citation_problems = check_citation_format(record)
    structural_problems = check_structural_completeness(record)

    print(f"\nCitation format: {'PASS' if not citation_problems else 'FAIL'}")
    for p in citation_problems:
        print(f"  - {p}")

    print(f"\nStructural completeness: {'PASS' if not structural_problems else 'FAIL'}")
    for p in structural_problems:
        print(f"  - {p}")

    gt_path = ground_truth_dir / output_path.name
    if gt_path.exists():
        ground_truth = json.loads(gt_path.read_text(encoding="utf-8"))
        matches, total = compare_to_ground_truth(record, ground_truth)
        print(f"\nGround-truth field/count comparison: {matches}/{total} match")

        must_not_assert = ground_truth.get("must_not_assert", [])
        if must_not_assert:
            flags = check_must_not_assert(record, must_not_assert)
            print(f"\nmust_not_assert heuristic check: {len(flags)} flag(s)")
            for f in flags:
                print(f"  - {f}")
            if not flags:
                print("  (no forbidden-claim keyword overlaps found)")
        print(
            "\nNOTE: this is a structural + heuristic check, not a full semantic "
            "comparison. For a true semantic diff against the fixture, use "
            "gaik's LLMJudge text-pair comparison or "
            "evaluation_layer/eval_methods/extraction_eval/evaluate.py."
        )
    else:
        print(f"\nNo ground-truth file found at {gt_path} -- skipping field comparison.")
        print("To compare against a fixture, copy it there with the same filename as the output.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output-file",
        default="output/meeting_record.json",
        help="Path to the PoC output JSON to evaluate (relative to the poc/ root)",
    )
    args = parser.parse_args()

    root = Path(__file__).parent.parent
    output_path = (root / args.output_file).resolve()
    ground_truth_dir = root / "evals" / "ground_truth"
    ground_truth_dir.mkdir(parents=True, exist_ok=True)
    run_evaluation(output_path, ground_truth_dir)
