"""Proof of Concept: Manufacturing Knowledge Assistant

Generated by GAIK Solution Configuration Wizard, then customized by the wizard
agent for this use case's role-based access control (RBAC) requirement, which
the stock RAGWorkflow template does not cover out of the box.

Pattern: rag (built on GAIK's RAGWorkflow building blocks: VisionRagParser,
Embedder, VectorStore, Retriever, AnswerGenerator's LLM client).

Why not a plain `RAGWorkflow(...).index_documents(...)` / `.ask(...)` call?
  - RAGWorkflow.index_documents() has no hook to attach custom per-chunk
    metadata, but pre-retrieval RBAC filtering requires a role_<role> boolean
    flag on every chunk (derived from access_manifest.json). So this script
    drives RAGWorkflow's own constituent parts directly (same parser/embedder/
    vector store/retriever it uses internally) to inject that metadata at
    ingestion time.
  - RAGWorkflow.ask() -> AnswerGenerator.generate() hardcodes temperature=0.0
    on every call, with no constructor or call-time override. The user
    explicitly requested temperature=1.0 and reasoning_effort="medium"
    (see config.yaml), so answer generation here calls the underlying chat
    client directly instead of going through AnswerGenerator.generate().

Usage:
    python run_poc.py --input <path-to-poc_input_bundle.json>

The bundle file points (with paths resolved relative to itself) to:
    - documents_directory: folder of source PDFs
    - access_manifest:      per-document classification + allowed_roles
    - query_set:            role-tagged questions to answer
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from pathlib import Path

import yaml
from dotenv import load_dotenv

load_dotenv()

from gaik.software_components.config import create_openai_client, get_openai_config  # noqa: E402
from gaik.software_components.RAG.embedder import Embedder  # noqa: E402
from gaik.software_components.RAG.rag_parser_vision import VisionRagParser  # noqa: E402
from gaik.software_components.RAG.retriever import Retriever  # noqa: E402
from gaik.software_components.RAG.vector_store import VectorStore  # noqa: E402

sys.path.insert(0, str(Path(__file__).parent))
from schemas.output_schema import RAGAnswerRecord  # noqa: E402

ROLES = ("employee", "manager")

# Below this cosine-similarity score, the best authorized match is considered
# too weak to answer from -- the response becomes an honest "not found"
# instead of a guess. Tune against real retrieval score distributions during
# Gate 3 if answers are wrongly refused or wrongly attempted.
NOT_FOUND_FLOOR = 0.2

ANSWER_PROMPT = (
    "You are an internal knowledge assistant for a manufacturing company. "
    "Answer the question using ONLY the information in the context below. "
    "Do not use any outside knowledge and do not guess.\n"
    "If the context does not contain enough information to answer, say plainly "
    "that the information was not found in the documents you have access to.\n"
    "If different parts of the context disagree, point out the disagreement and "
    "mention both sources by name.\n"
    "Preserve exact numbers, currency amounts, units, and percentages exactly as "
    "written in the context (e.g. 'EUR 180', '250 operating hours', '1.8 bar').\n"
    "Answer in plain prose. Do not invent bracketed citations yourself -- "
    "citations are attached separately by the pipeline.\n\n"
    "Context:\n{context}\n\n"
    "Question: {question}"
)


def load_config() -> dict:
    config_path = Path(__file__).parent / "config.yaml"
    with open(config_path, encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_bundle(input_path: Path) -> tuple[Path, dict, list, dict]:
    """Load poc_input_bundle.json and resolve the files it points to, all
    relative to the bundle file's own location (not the cwd)."""
    bundle = json.loads(input_path.read_text(encoding="utf-8"))
    base_dir = input_path.parent

    documents_dir = base_dir / bundle["documents_directory"]
    access_manifest = json.loads((base_dir / bundle["access_manifest"]).read_text(encoding="utf-8"))
    query_set = json.loads((base_dir / bundle["query_set"]).read_text(encoding="utf-8"))

    return documents_dir, access_manifest, query_set["queries"], bundle


def build_role_flags(access_manifest: dict) -> dict[str, dict[str, bool]]:
    """Map each document's filename -> {"role_employee": bool, "role_manager": bool, ...}
    from access_manifest.json's allowed_roles, so retrieval can filter on it."""
    flags_by_filename: dict[str, dict[str, bool]] = {}
    for doc in access_manifest["documents"]:
        filename = Path(doc["file"]).name
        flags_by_filename[filename] = {
            f"role_{role}": role in doc.get("allowed_roles", []) for role in ROLES
        }
    return flags_by_filename


def index_documents(
    parser: VisionRagParser,
    embedder: Embedder,
    vector_store: VectorStore,
    documents_dir: Path,
    flags_by_filename: dict[str, dict[str, bool]],
) -> int:
    """Parse each PDF, tag every chunk with its document's role_<role> flags,
    then embed and store. This is index_documents()'s job, done manually
    because RAGWorkflow.index_documents() has no metadata-injection hook."""
    all_chunks = []
    for pdf_path in sorted(documents_dir.glob("*.pdf")):
        filename = pdf_path.name  # keep the extension: citations must read "foo.pdf"
        chunks = parser.convert_doc_to_chunks_with_vision(str(pdf_path), document_name=filename)
        flags = flags_by_filename.get(filename, dict.fromkeys((f"role_{r}" for r in ROLES), False))
        for chunk in chunks:
            chunk.metadata.update(flags)
        all_chunks.extend(chunks)
        print(f"  Indexed {filename}: {len(chunks)} chunk(s), flags={flags}")

    if not all_chunks:
        return 0
    embeddings, docs = embedder.embed(all_chunks)
    vector_store.add(docs, embeddings)
    return len(all_chunks)


def _citation_pairs(chunks) -> list[tuple[str, int]]:
    pairs = set()
    for doc in chunks:
        page = doc.metadata.get("page_number")
        name = doc.metadata.get("document_name")
        if name and isinstance(page, int):
            pairs.add((name, page))
    return sorted(pairs)


def _call_llm(client, model: str, question: str, context_chunks, temperature: float, reasoning_effort: str | None) -> str:
    context_text = "\n\n".join(
        f"[Document: {d.metadata.get('document_name')}, Page: {d.metadata.get('page_number')}]\n{d.page_content}"
        for d in context_chunks
    )
    prompt = ANSWER_PROMPT.format(context=context_text, question=question)
    messages = [{"role": "user", "content": prompt}]

    kwargs = {"model": model, "messages": messages, "temperature": temperature}
    if reasoning_effort:
        kwargs["reasoning_effort"] = reasoning_effort
    try:
        response = client.chat.completions.create(**kwargs)
    except Exception as exc:  # deployment/model may reject reasoning_effort
        if reasoning_effort:
            print(f"  (reasoning_effort='{reasoning_effort}' rejected by the API: {exc}; retrying without it)")
            kwargs.pop("reasoning_effort", None)
            response = client.chat.completions.create(**kwargs)
        else:
            raise
    if not response.choices:
        return ""
    return response.choices[0].message.content or ""


def classify_and_answer(
    retriever: Retriever,
    client,
    model: str,
    temperature: float,
    reasoning_effort: str | None,
    query_id: str,
    role: str,
    question: str,
) -> RAGAnswerRecord:
    role_key = f"role_{role}"

    # The ONLY chunks ever used to build the answer or citations.
    authorized_chunks = retriever.search(question, top_k=4, filters={role_key: True}, include_scores=True)
    # Internal-only lookup across the full corpus, used SOLELY to tell apart
    # "this role has no access to the relevant document" from "no document
    # covers this topic at all". Its content is never surfaced.
    full_chunks = retriever.search(question, top_k=4, filters=None, include_scores=True)

    def score(d) -> float:
        return d.metadata.get("relevance_score", float("-inf"))

    best_authorized_score = score(authorized_chunks[0]) if authorized_chunks else float("-inf")
    best_full = full_chunks[0] if full_chunks else None

    is_restricted_topic = (
        best_full is not None
        and not best_full.metadata.get(role_key, False)
        and score(best_full) > best_authorized_score
    )

    if is_restricted_topic:
        return RAGAnswerRecord(
            query_id=query_id,
            role=role,
            question=question,
            access_decision="denied",
            answer="I'm not able to share that information -- it is restricted to a different role.",
            citations=[],
            refusal_reason="The requested information is in a document not permitted for your role.",
        )

    if not authorized_chunks or best_authorized_score < NOT_FOUND_FLOOR:
        return RAGAnswerRecord(
            query_id=query_id,
            role=role,
            question=question,
            access_decision="allowed",
            answer="I could not find information about this in the documents available to your role.",
            citations=[],
            refusal_reason="No sufficiently relevant content was found in the authorized document set.",
        )

    answer_text = _call_llm(client, model, question, authorized_chunks, temperature, reasoning_effort)
    citations = _citation_pairs(authorized_chunks)

    return RAGAnswerRecord(
        query_id=query_id,
        role=role,
        question=question,
        access_decision="allowed",
        answer=answer_text.strip(),
        citations=citations,
        refusal_reason=None,
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Manufacturing Knowledge Assistant PoC")
    parser.add_argument(
        "--input",
        required=True,
        help="Path to poc_input_bundle.json (documents/access_manifest/query_set are resolved relative to it)",
    )
    args = parser.parse_args()

    config = load_config()
    output_dir = Path(__file__).parent / config.get("paths", {}).get("output", "output")
    output_dir.mkdir(parents=True, exist_ok=True)

    input_path = Path(args.input).expanduser().resolve()
    documents_dir, access_manifest, queries, _bundle = load_bundle(input_path)

    use_azure = bool(config.get("use_azure", True))
    api_config = get_openai_config(use_azure=use_azure)
    model = config.get("models", {}).get("generation", api_config["model"])
    temperature = float(config.get("models", {}).get("temperature", 0.0))
    reasoning_effort = config.get("models", {}).get("reasoning_effort")

    embedding_model = os.getenv("RAG_EMBEDDING_DEPLOYMENT") or config.get("models", {}).get("embedding")

    # Fresh index every run so re-running the PoC is repeatable and doesn't
    # accumulate duplicate chunks across executions.
    persist_path = Path(__file__).parent / "chroma_store"
    if persist_path.exists():
        shutil.rmtree(persist_path)

    print("Setting up RAG components...")
    vision_parser = VisionRagParser(vision_config=api_config)
    embedder = Embedder(config=api_config, model=embedding_model)
    vector_store = VectorStore(persist=True, persist_path=str(persist_path), collection_name="gaik_rag_manufacturing_kb")
    retriever = Retriever(embedder=embedder, vector_store=vector_store, top_k=4)
    client = create_openai_client(api_config)

    flags_by_filename = build_role_flags(access_manifest)

    print(f"Indexing documents from {documents_dir} ...")
    num_chunks = index_documents(vision_parser, embedder, vector_store, documents_dir, flags_by_filename)
    print(f"Indexed {num_chunks} chunk(s) total.\n")

    records: list[RAGAnswerRecord] = []
    for q in queries:
        print(f"Answering {q['query_id']} (role={q['role']}): {q['question']}")
        record = classify_and_answer(
            retriever, client, model, temperature, reasoning_effort,
            q["query_id"], q["role"], q["question"],
        )
        print(f"  -> access_decision={record.access_decision}, citations={record.citations}")
        records.append(record)

    if not records:
        print("ERROR: no records produced -- check query_set.json", file=sys.stderr)
        sys.exit(1)

    result_path = output_dir / "answer_records.json"
    result_path.write_text(
        json.dumps([r.model_dump() for r in records], indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(f"\nSaved {len(records)} record(s) to {result_path}")


if __name__ == "__main__":
    main()
